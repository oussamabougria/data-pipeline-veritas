"""
veritas_consumer.py
====================
Kafka → Score → TimescaleDB

Reads messages from veritas.raw, computes C(v) = tau * delta * alpha,
writes scored rows into veritas.scored_observations.

This is the Critical Path replacement for Flink during development/demo.
It is single-threaded but fast enough for simulator loads.

USAGE:
    python veritas_consumer.py

RULES:
    1. _vlog — never log
    2. All scoring values are Decimal — never float
    3. Every scored row includes skill_id, skill_version, tau, delta, alpha
    4. confidence is GENERATED by the DB — never written by Python
    5. physics_ok written as NULL — Airflow enriches it async
"""

