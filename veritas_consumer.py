# ── State ─────────────────────────────────────────────────────────────────────

# Per-sensor sliding windows for scoring
sensor_windows: dict[str, deque] = {}
sensor_last_ts: dict[str, float] = {}
sensor_expected_hz: dict[str, float] = {
    "INERTIAL":   1.0,
    "CUMULATIVE": 0.2,
    "CYCLICAL":   10.0,
    "BINARY":     2.0,
}

# Metrics
stats = {
    "consumed": 0,
    "scored":   0,
    "anomalies": 0,
    "malformed": 0,
    "errors":   0,
    "start":    time.time(),
}

RUNNING = True

# ── Decimal precision ─────────────────────────────────────────────────────────

Q = Decimal("0.0001")  # quantize target — matches NUMERIC(6,4)

def _q(v: Decimal) -> Decimal:
    return v.quantize(Q, rounding=ROUND_HALF_UP)

def _clamp(v: Decimal) -> Decimal:
    return max(Decimal("0.0000"), min(Decimal("1.0000"), v))

# ── Scoring functions ─────────────────────────────────────────────────────────

def compute_tau(sensor_id: str, archetype: str, now_ts: float) -> Decimal:
    """
    τ(T) — temporal coherence.
    Gaussian decay based on how late/early this reading arrived.
    """
    last = sensor_last_ts.get(sensor_id)
    if last is None:
        sensor_last_ts[sensor_id] = now_ts
        return _q(Decimal("1.0000"))

    hz = sensor_expected_hz.get(archetype.upper(), 1.0)
    expected_period = 1.0 / hz
    actual_period = now_ts - last
    sensor_last_ts[sensor_id] = now_ts

    if actual_period <= 0:
        return _q(Decimal("0.5000"))

    ratio = Decimal(str(actual_period / expected_period))
    exponent = -(ratio - Decimal("1")) ** 2
    result = Decimal(str(math.exp(float(exponent))))
    return _q(_clamp(result))


def compute_delta(sensor_id: str, value: float) -> Decimal:
    """
    δ(n) — density / completeness factor.
    Ratio of received samples to expected samples in the window.
    """
    if sensor_id not in sensor_windows:
        sensor_windows[sensor_id] = deque(maxlen=WINDOW_SIZE)

    sensor_windows[sensor_id].append(value)
    n = len(sensor_windows[sensor_id])
    result = Decimal(str(n)) / Decimal(str(WINDOW_SIZE))
    return _q(_clamp(result))


def compute_alpha(sensor_id: str, value: float, archetype: str) -> Decimal:
    """
    α(σ) — amplitude stability factor.
    Exponential decay based on how volatile the signal is vs expected.
    """
    window = sensor_windows.get(sensor_id)
    if not window or len(window) < 3:
        return _q(Decimal("0.8000"))  # not enough data yet — assume ok

    try:
        observed_std = stdev(list(window))
    except Exception:
        return _q(Decimal("0.8000"))

    # Expected std by archetype
    expected_stds = {
        "INERTIAL":   2.0,
        "CUMULATIVE": 5.0,
        "CYCLICAL":   1.5,
        "BINARY":     0.5,
    }
    expected_std = expected_stds.get(archetype.upper(), 2.0)

    if expected_std <= 0 or observed_std < 0:
        return _q(Decimal("0.5000"))

    ratio = Decimal(str(observed_std / expected_std))
    exponent = -abs(ratio - Decimal("1"))
    result = Decimal(str(math.exp(float(exponent))))
    return _q(_clamp(result))


def detect_anomaly(
    value: float,
    archetype: str,
    tau: Decimal,
    delta: Decimal,
    alpha: Decimal,
    confidence: Decimal,
) -> tuple[bool, str | None, Decimal | None]:
    """
    Returns (is_anomaly, anomaly_label, anomaly_score).
    """
    if confidence < ANOMALY_THRESHOLD:
        # Determine most likely cause
        factors = {"tau": tau, "delta": delta, "alpha": alpha}
        weakest = min(factors, key=lambda k: factors[k])
        labels = {
            "tau":   "TIMING_ANOMALY",
            "delta": "DENSITY_DROP",
            "alpha": "VOLATILITY_SPIKE",
        }
        label = labels[weakest]
        score = _q(Decimal("1.0000") - confidence)
        return True, label, score

    # Physical bounds check by archetype
    bounds = {
        "INERTIAL":   (-50.0, 500.0),
        "CUMULATIVE": (0.0, 1000.0),
        "CYCLICAL":   (0.0, 200.0),
        "BINARY":     (0.0, 1.0),
    }
    lo, hi = bounds.get(archetype.upper(), (-1e6, 1e6))
    if not (lo <= value <= hi):
        return True, "OUT_OF_PHYSICAL_BOUNDS", _q(Decimal("0.9500"))

    return False, None, None


# ── DB writer ─────────────────────────────────────────────────────────────────

def get_db_conn():
    try:
        conn = psycopg2.connect(DB_CONN)
    except UnicodeDecodeError as exc:
        raise RuntimeError(
            "PostgreSQL connection failed and psycopg2 masked the server error with a UnicodeDecodeError. "
            "On this Windows setup, run the consumer inside Docker or validate the DB auth/network path separately."
        ) from exc
    conn.autocommit = False
    return conn


def ensure_runtime_metrics(conn) -> None:
    """Create the small runtime table used by the dashboard terminal panel."""
    try:
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS veritas.consumer_runtime_metrics (
                    id TEXT PRIMARY KEY,
                    consumed BIGINT NOT NULL DEFAULT 0,
                    scored BIGINT NOT NULL DEFAULT 0,
                    anomalies BIGINT NOT NULL DEFAULT 0,
                    malformed BIGINT NOT NULL DEFAULT 0,
                    errors BIGINT NOT NULL DEFAULT 0,
                    rate_per_sec NUMERIC(12, 2) NOT NULL DEFAULT 0,
                    latest_log TEXT,
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
                )
            """)
        conn.commit()
    except Exception as e:
        conn.rollback()
        _vlog.warning("Runtime metrics table unavailable: %s", e)


def write_runtime_metrics(conn, latest_log: str | None = None) -> None:
    elapsed = max(time.time() - stats["start"], 0.001)
    rate = stats["scored"] / elapsed
    if latest_log is None:
        latest_log = (
            f"scored={stats['scored']} anomalies={stats['anomalies']} "
            f"malformed={stats['malformed']} rate={rate:.1f}/s"
        )
    try:
        with conn.cursor() as cur:
            cur.execute("""
                INSERT INTO veritas.consumer_runtime_metrics (
                    id, consumed, scored, anomalies, malformed, errors,
                    rate_per_sec, latest_log, updated_at
                ) VALUES (
                    'veritas_consumer', %(consumed)s, %(scored)s, %(anomalies)s,
                    %(malformed)s, %(errors)s, %(rate_per_sec)s, %(latest_log)s, NOW()
                )
                ON CONFLICT (id) DO UPDATE SET
                    consumed = EXCLUDED.consumed,
                    scored = EXCLUDED.scored,
                    anomalies = EXCLUDED.anomalies,
                    malformed = EXCLUDED.malformed,
                    errors = EXCLUDED.errors,
                    rate_per_sec = EXCLUDED.rate_per_sec,
                    latest_log = EXCLUDED.latest_log,
                    updated_at = EXCLUDED.updated_at
            """, {
                "consumed": stats["consumed"],
                "scored": stats["scored"],
                "anomalies": stats["anomalies"],
                "malformed": stats["malformed"],
                "errors": stats["errors"],
                "rate_per_sec": f"{rate:.2f}",
                "latest_log": latest_log[:500],
            })
        conn.commit()
    except Exception as e:
        conn.rollback()
        _vlog.warning("Runtime metrics write failed: %s", e)


def _clean_sensor_id(value: object) -> str:
    return str(value or "UNKNOWN").strip()[:64]


def _clean_unit(value: object) -> str:
    return str(value or "").strip()[:16]


def _clean_archetype(value: object) -> str:
    archetype = str(value or "INERTIAL").strip().upper()
    if archetype not in {"INERTIAL", "CUMULATIVE", "CYCLICAL", "BINARY"}:
        return "INERTIAL"
    return archetype


def write_scored_row(conn, msg: dict, tau: Decimal, delta: Decimal, alpha: Decimal,
                     is_anomaly: bool, anomaly_label: str | None,
                     anomaly_score: Decimal | None) -> bool:
    """
    Insert one row into veritas.scored_observations.
    confidence is GENERATED by the DB — do not insert it.
    physics_ok is NULL — Airflow enriches it async.
    """
    try:
        with conn.cursor() as cur:
            cur.execute("""
                INSERT INTO veritas.scored_observations (
                    sensor_id, ts, value, unit, archetype,
                    tau, delta, alpha,
                    skill_id, skill_version,
                    is_anomaly, anomaly_label, anomaly_score,
                    physics_ok,
                    scored_at
                ) VALUES (
                    %(sensor_id)s, %(ts)s, %(value)s, %(unit)s, %(archetype)s,
                    %(tau)s, %(delta)s, %(alpha)s,
                    %(skill_id)s, %(skill_version)s,
                    %(is_anomaly)s, %(anomaly_label)s, %(anomaly_score)s,
                    NULL,
                    NOW()
                )
            """, {
                "sensor_id":    _clean_sensor_id(msg.get("sensor_id")),
                "ts":           msg.get("observed_at", datetime.now(timezone.utc).isoformat()),
                "value":        msg.get("value"),
                "unit":         _clean_unit(msg.get("unit")),
                "archetype":    _clean_archetype(msg.get("archetype")),
                "tau":          str(tau),
                "delta":        str(delta),
                "alpha":        str(alpha),
                "skill_id":     SKILL_ID,
                "skill_version": SKILL_VERSION,
                "is_anomaly":   is_anomaly,
                "anomaly_label": anomaly_label,
                "anomaly_score": str(anomaly_score) if anomaly_score else None,
            })
        conn.commit()
        return True
    except Exception as e:
        conn.rollback()
        _vlog.error("DB write failed: %s", e)
        return False


# ── Main consumer loop ────────────────────────────────────────────────────────

def main():
    global RUNNING

    def shutdown(sig, frame):
        global RUNNING
        RUNNING = False
        _vlog.info("Shutting down consumer...")

    signal.signal(signal.SIGINT, shutdown)
    signal.signal(signal.SIGTERM, shutdown)

    _vlog.info("Connecting to Kafka at %s -> topic %s", KAFKA_BOOTSTRAP, TOPIC)

    try:
        consumer = KafkaConsumer(
            TOPIC,
            bootstrap_servers=KAFKA_BOOTSTRAP,
            group_id=GROUP_ID,
            auto_offset_reset="earliest",
            enable_auto_commit=True,
            value_deserializer=lambda m: m,   # raw bytes — we parse manually
            consumer_timeout_ms=1000,
        )
        _vlog.info("Kafka connected.")
    except NoBrokersAvailable:
        _vlog.error("Cannot reach Kafka at %s", KAFKA_BOOTSTRAP)
        sys.exit(1)

    _vlog.info("Connecting to TimescaleDB...")
    try:
        conn = get_db_conn()
        _vlog.info("DB connected.")
        ensure_runtime_metrics(conn)
        write_runtime_metrics(conn, "Consumer connected. Waiting for simulator events.")
    except Exception as e:
        _vlog.error("Cannot connect to DB: %s", e)
        sys.exit(1)

    _vlog.info("Consumer running. Ctrl-C to stop.\n")
    router = VeritasRouter()
    pipeline = VeritasPipeline()

    while RUNNING:
        try:
            for message in consumer:
                if not RUNNING:
                    break

                stats["consumed"] += 1
                now_ts = time.time()

                # ── Parse ──────────────────────────────────────────────────
                try:
                    raw = message.value
                    msg = json.loads(raw.decode("utf-8", errors="ignore"))
                    if not isinstance(msg, dict):
                        raise ValueError("not a dict")
                    sensor_id = _clean_sensor_id(msg.get("sensor_id"))
                    value = msg.get("value")
                    if not sensor_id or value is None:
                        raise ValueError("missing sensor_id or value")
                    value = float(value)
                    if not math.isfinite(value):
                        raise ValueError("non-finite value")
                    archetype = _clean_archetype(msg.get("archetype"))
                except Exception:
                    stats["malformed"] += 1
                    write_runtime_metrics(conn)
                    continue

                # ── Score ──────────────────────────────────────────────────
                event_df = pd.DataFrame([msg])
                source = router.route(
                    connector="kafka",
                    columns=list(event_df.columns),
                    source_name=TOPIC,
                    config={"topic": TOPIC},
                )
                run = pipeline.run(df=event_df, source=source)
                value_profile = next(
                    (p for p in run.profiles if p.column == "value"),
                    run.profiles[0] if run.profiles else None,
                )
                if value_profile is None:
                    raise ValueError("pipeline produced no scored profiles")

                tau = _q(Decimal(str(value_profile.tau)))
                delta = _q(Decimal(str(value_profile.delta)))
                alpha = _q(Decimal(str(value_profile.alpha)))

                # confidence = tau * delta * alpha — computed here for anomaly
                # detection only. The DB GENERATED column is the source of truth.
                confidence = _q(Decimal(str(value_profile.confidence)))

                is_anomaly, anomaly_label, anomaly_score = detect_anomaly(
                    value, archetype, tau, delta, alpha, confidence
                )

                # ── Write ──────────────────────────────────────────────────
                ok = write_scored_row(
                    conn, msg, tau, delta, alpha,
                    is_anomaly, anomaly_label, anomaly_score
                )

                if ok:
                    stats["scored"] += 1
                    if is_anomaly:
                        stats["anomalies"] += 1
                    if stats["scored"] % 50 == 0:
                        elapsed = time.time() - stats["start"]
                        rate = stats["scored"] / elapsed
                        latest_log = (
                            "scored=%d  anomalies=%d  malformed=%d  rate=%.1f/s"
                            % (
                                stats["scored"], stats["anomalies"],
                                stats["malformed"], rate
                            )
                        )
                        _vlog.info(
                            "scored=%d  anomalies=%d  malformed=%d  rate=%.1f/s",
                            stats["scored"], stats["anomalies"],
                            stats["malformed"], rate
                        )
                        write_runtime_metrics(conn, latest_log)
                else:
                    stats["errors"] += 1
                    write_runtime_metrics(conn)
                    # Reconnect on DB error
                    try:
                        conn.close()
                    except Exception:
                        pass
                    try:
                        conn = get_db_conn()
                    except Exception as e:
                        _vlog.error("DB reconnect failed: %s", e)
                        time.sleep(2)

        except Exception as e:
            _vlog.error("Consumer loop error: %s", e)
            time.sleep(1)

    # ── Shutdown ───────────────────────────────────────────────────────────
    consumer.close()
    conn.close()

    elapsed = time.time() - stats["start"]
    print(f"\n{'='*50}")
    print(f"FINAL REPORT")
    print(f"{'='*50}")
    print(f"Consumed  : {stats['consumed']:,}")
    print(f"Scored    : {stats['scored']:,}")
    print(f"Anomalies : {stats['anomalies']:,}")
    print(f"Malformed : {stats['malformed']:,}")
    print(f"Errors    : {stats['errors']:,}")
    print(f"Rate      : {stats['scored']/elapsed:.1f} msg/sec")
    print(f"Duration  : {int(elapsed)}s")


if __name__ == "__main__":
    main()
